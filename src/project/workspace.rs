use std::{collections::BTreeMap, fs, io::ErrorKind, path::Path};

use anyhow::{Context, Result, bail};
use jsonc_parser::{ParseOptions, cst::CstRootNode};
use serde_json::{Map, Value, json};

use super::manifest::{ApplicationDefinition, Dependencies};

const GENERATED_HEADER: &str = "# Generated by wr setup. Do not edit.\n";
const WORLD: &str = include_str!("../../wit/world.wit");
const KV_WORLD: &str = include_str!("../../wit/deps/kv/store.wit");
const SQL_WORLD: &str = include_str!("../../wit/deps/sql/database.wit");
const EXTRA_INCLUDES_SETTING: &str = "rust-analyzer.vfs.extraIncludes";
const FUNCTIONS_INCLUDE: &str = "${workspaceFolder}/functions";
const LIBS_INCLUDE: &str = "${workspaceFolder}/libs";

pub(crate) fn discover_functions(directory: &Path) -> Result<Vec<String>> {
    let sources = directory.join("functions");
    let entries = fs::read_dir(&sources)
        .with_context(|| format!("reading function directory {}", sources.display()))?;
    let mut functions = Vec::new();
    for entry in entries {
        let entry = entry.with_context(|| format!("reading {}", sources.display()))?;
        let path = entry.path();
        if path.extension().is_none_or(|extension| extension != "rs") || !path.is_file() {
            continue;
        }
        let name = path.file_stem().and_then(|name| name.to_str());
        let Some(name) = name.filter(|name| crate::identifier::is_valid(name)) else {
            bail!(
                "invalid function filename {}: expected a lowercase identifier of at most 64 letters, digits, or hyphens, starting with a letter",
                path.display()
            );
        };
        functions.push(name.to_owned());
    }
    functions.sort_unstable();
    Ok(functions)
}

pub(super) fn library_name(name: &str) -> String {
    format!("wr_function_{}", name.replace('-', "_"))
}

/// Render workspace files, relative to the application's directory.
/// Merge existing ignore entries and editor settings into the generated files.
/// Source files remain in the application's `functions` directory.
pub(crate) fn generate(
    directory: &Path,
    application: &ApplicationDefinition,
    function_names: &[String],
) -> Result<BTreeMap<String, String>> {
    let libs_path = directory.join("libs/mod.rs");
    let has_libs = match fs::metadata(&libs_path) {
        Ok(metadata) if metadata.is_file() => true,
        Ok(_) => bail!("{} must be a file", libs_path.display()),
        Err(error) if error.kind() == ErrorKind::NotFound => false,
        Err(error) => {
            return Err(error).with_context(|| format!("reading {}", libs_path.display()));
        }
    };
    let common = &application.dependencies;
    let empty = BTreeMap::new();
    let functions: BTreeMap<_, _> = function_names
        .iter()
        .map(|name| {
            let dependencies = application
                .functions
                .get(name)
                .map_or(&empty, |function| &function.dependencies);
            (name.clone(), dependencies)
        })
        .collect();
    if functions.is_empty() {
        bail!("setup needs at least one function in functions/*.rs");
    }
    if common.contains_key("wit-bindgen")
        || functions
            .values()
            .any(|local| local.contains_key("wit-bindgen"))
    {
        bail!("wit-bindgen is managed by wr and must not be declared as an application dependency");
    }

    let mut files = BTreeMap::from([(
        "Cargo.toml".to_owned(),
        render_workspace_manifest(common, &functions)?,
    )]);
    files.insert(".wr/wit/world.wit".to_owned(), WORLD.to_owned());
    files.insert(".wr/wit/deps/kv/store.wit".to_owned(), KV_WORLD.to_owned());
    files.insert(
        ".wr/wit/deps/sql/database.wit".to_owned(),
        SQL_WORLD.to_owned(),
    );

    for (name, local) in &functions {
        let dependencies = build_function_dependencies(name, common, local)?;
        files.insert(
            format!(".wr/functions/{name}/Cargo.toml"),
            render_function_manifest(name, dependencies)?,
        );
        files.insert(
            format!(".wr/functions/{name}/lib.rs"),
            render_entry_point(name, has_libs),
        );
    }
    files.insert(".gitignore".to_owned(), generate_gitignore(directory)?);
    files.insert(
        ".vscode/settings.json".to_owned(),
        generate_editor_settings(directory, has_libs)?,
    );
    Ok(files)
}

fn generate_editor_settings(directory: &Path, has_libs: bool) -> Result<String> {
    let mut required_includes = vec![FUNCTIONS_INCLUDE];
    if has_libs {
        required_includes.push(LIBS_INCLUDE);
    }
    let path = directory.join(".vscode/settings.json");
    let contents = match fs::read_to_string(&path) {
        Ok(contents) => contents,
        Err(error) if error.kind() == ErrorKind::NotFound => "{\n}\n".to_owned(),
        Err(error) => return Err(error).with_context(|| format!("reading {}", path.display())),
    };
    let root = CstRootNode::parse(&contents, &ParseOptions::default())
        .with_context(|| format!("parsing {}", path.display()))?;
    let settings = root
        .object_value_or_create()
        .with_context(|| format!("{}: expected a settings object", path.display()))?;
    if let Some(property) = settings.get(EXTRA_INCLUDES_SETTING) {
        let expected = || {
            format!(
                "{}: {EXTRA_INCLUDES_SETTING} must be an array of strings",
                path.display()
            )
        };
        let includes = property.array_value().with_context(expected)?;
        let paths = includes
            .elements()
            .iter()
            .map(|element| serde_json::from_str::<String>(&element.to_string()))
            .collect::<Result<Vec<_>, _>>()
            .with_context(expected)?;
        for required in required_includes {
            if !paths.iter().any(|entry| entry == required) {
                includes.append(required.into());
            }
        }
    } else {
        settings.append(EXTRA_INCLUDES_SETTING, required_includes.into());
    }
    Ok(root.to_string())
}

/// Preserve existing ignore entries and append missing rules for setup and build output.
fn generate_gitignore(directory: &Path) -> Result<String> {
    let path = directory.join(".gitignore");
    let mut contents = match fs::read_to_string(&path) {
        Ok(contents) => contents,
        Err(error) if error.kind() == ErrorKind::NotFound => String::new(),
        Err(error) => return Err(error).with_context(|| format!("reading {}", path.display())),
    };

    for rule in [".wr/", "/Cargo.toml", "/target/", "/.wr-data/"] {
        if contents.lines().any(|line| line == rule) {
            continue;
        }
        if !contents.is_empty() && !contents.ends_with('\n') {
            contents.push('\n');
        }
        contents.push_str(rule);
        contents.push('\n');
    }
    Ok(contents)
}

/// Write generated files, creating their parent directories and replacing existing contents.
pub(crate) fn write_workspace(directory: &Path, files: &BTreeMap<String, String>) -> Result<()> {
    ensure_generated_workspace_manifest(&directory.join("Cargo.toml"), "overwrite")?;
    for (name, contents) in files {
        let path = directory.join(name);
        match fs::read(&path) {
            Ok(existing) if existing == contents.as_bytes() => continue,
            Ok(_) => {}
            Err(error) if error.kind() == ErrorKind::NotFound => {}
            Err(error) => {
                return Err(error)
                    .with_context(|| format!("reading generated file {}", path.display()));
            }
        }
        let parent = path
            .parent()
            .expect("generated workspace files have a parent directory");
        fs::create_dir_all(parent)
            .with_context(|| format!("creating directory {}", parent.display()))?;
        fs::write(&path, contents)
            .with_context(|| format!("writing generated file {}", path.display()))?;
    }
    Ok(())
}

pub(crate) fn clean_workspace(directory: &Path) -> Result<()> {
    if !fs::metadata(directory)
        .with_context(|| format!("reading application directory {}", directory.display()))?
        .is_dir()
    {
        bail!("{} is not an application directory", directory.display());
    }
    ensure_generated_workspace_manifest(&directory.join("Cargo.toml"), "remove")?;
    for name in [".wr", "target", "Cargo.toml"] {
        let path = directory.join(name);
        let metadata = match fs::symlink_metadata(&path) {
            Ok(metadata) => metadata,
            Err(error) if error.kind() == ErrorKind::NotFound => continue,
            Err(error) => return Err(error).with_context(|| format!("reading {}", path.display())),
        };
        let result = if metadata.is_dir() {
            fs::remove_dir_all(&path)
        } else {
            fs::remove_file(&path)
        };
        result.with_context(|| format!("removing {}", path.display()))?;
    }
    Ok(())
}

fn ensure_generated_workspace_manifest(path: &Path, operation: &str) -> Result<()> {
    match fs::read_to_string(path) {
        Ok(contents) if contents.starts_with(GENERATED_HEADER) => Ok(()),
        Ok(_) => bail!(
            "refusing to {operation} {}: not generated by wr setup",
            path.display()
        ),
        Err(error) if error.kind() == ErrorKind::NotFound => Ok(()),
        Err(error) => Err(error).with_context(|| format!("reading {}", path.display())),
    }
}

fn render_workspace_manifest(
    common: &Dependencies,
    functions: &BTreeMap<String, &Dependencies>,
) -> Result<String> {
    let members: Vec<_> = functions
        .keys()
        .map(|name| format!(".wr/functions/{name}"))
        .collect();
    let workspace = json!({
        "workspace": {
            "members": members,
            "resolver": "3",
            "dependencies": common,
        },
    });
    Ok(format!(
        "{GENERATED_HEADER}{}",
        toml::to_string_pretty(&workspace)?
    ))
}

fn build_function_dependencies(
    name: &str,
    common: &Dependencies,
    local: &Dependencies,
) -> Result<Map<String, Value>> {
    let mut dependencies = Map::new();
    dependencies.insert("wit-bindgen".to_owned(), json!("0.46"));
    for dependency in common.keys() {
        dependencies.insert(dependency.clone(), json!({ "workspace": true }));
    }
    for (dependency, definition) in local {
        if common.contains_key(dependency) {
            bail!("function {name}: dependency {dependency} is declared both globally and locally");
        }
        dependencies.insert(dependency.clone(), serde_json::to_value(definition)?);
    }
    Ok(dependencies)
}

fn render_function_manifest(name: &str, dependencies: Map<String, Value>) -> Result<String> {
    let manifest = json!({
        "package": {
            "name": format!("wr-function-{name}"),
            "version": "0.1.0",
            "edition": "2024",
            "publish": false,
            "workspace": "../../..",
        },
        "lib": {
            "name": library_name(name),
            "crate-type": ["cdylib"],
            "path": "lib.rs",
        },
        "dependencies": dependencies,
    });
    Ok(toml::to_string_pretty(&manifest)?)
}

fn render_entry_point(name: &str, has_libs: bool) -> String {
    let libs = if has_libs {
        "#[path = \"../../../libs/mod.rs\"]\npub mod libs;\n\n"
    } else {
        ""
    };
    format!(
        "wit_bindgen::generate!({{\n    path: \"../../wit\",\n    world: \"http-function\",\n    generate_all,\n}});\n\npub use exports::local::http::handler::{{Request, Response}};\npub use local::kv::store as kv;\npub use local::sql::database as sql;\n\n{libs}#[path = \"../../../functions/{name}.rs\"]\nmod function;\n\nstruct Component;\n\nimpl exports::local::http::handler::Guest for Component {{\n    fn handle(request: Request) -> Response {{\n        function::handle(request)\n    }}\n}}\n\nexport!(Component);\n"
    )
}
