use std::{collections::BTreeMap, fs, io::ErrorKind, path::Path};

use anyhow::{Context, Result, bail};
use serde::{Deserialize, Serialize};
use serde_json::{Map, Value, json};

pub type Dependencies = BTreeMap<String, Dependency>;

const GENERATED_HEADER: &str = "# Generated by wr setup. Do not edit.\n";

#[derive(Deserialize, Serialize)]
#[serde(untagged)]
pub enum Dependency {
    Version(String),
    Detailed(DependencyDetails),
}

#[derive(Deserialize, Serialize)]
#[serde(deny_unknown_fields, rename_all = "kebab-case")]
pub struct DependencyDetails {
    pub version: String,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub features: Vec<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub default_features: Option<bool>,
}

/// Render workspace files, relative to the application's directory.
/// Read existing ignore entries and include the merged `.gitignore` contents.
/// Source files remain in the application's `functions` directory.
pub fn generate(
    directory: &Path,
    common: &Dependencies,
    functions: &BTreeMap<String, &Dependencies>,
) -> Result<BTreeMap<String, String>> {
    if functions.is_empty() {
        bail!("setup needs at least one source function (omit its module field)");
    }

    let mut files = BTreeMap::from([(
        "Cargo.toml".to_owned(),
        render_workspace_manifest(common, functions)?,
    )]);

    for (name, local) in functions {
        let dependencies = build_function_dependencies(name, common, local)?;
        files.insert(
            format!(".wr/functions/{name}/Cargo.toml"),
            render_function_manifest(name, dependencies)?,
        );
    }
    files.insert(".gitignore".to_owned(), generate_gitignore(directory)?);
    Ok(files)
}

/// Preserve existing ignore entries and append missing rules for setup and build output.
fn generate_gitignore(directory: &Path) -> Result<String> {
    let path = directory.join(".gitignore");
    let mut contents = match fs::read_to_string(&path) {
        Ok(contents) => contents,
        Err(error) if error.kind() == ErrorKind::NotFound => String::new(),
        Err(error) => return Err(error).with_context(|| format!("reading {}", path.display())),
    };

    for rule in [".wr/", "/Cargo.toml", "/target/"] {
        if contents.lines().any(|line| line == rule) {
            continue;
        }
        if !contents.is_empty() && !contents.ends_with('\n') {
            contents.push('\n');
        }
        contents.push_str(rule);
        contents.push('\n');
    }
    Ok(contents)
}

/// Write generated files, creating their parent directories and replacing existing contents.
pub fn write_workspace(directory: &Path, files: &BTreeMap<String, String>) -> Result<()> {
    ensure_generated_workspace_manifest(&directory.join("Cargo.toml"))?;
    for (name, contents) in files {
        let path = directory.join(name);
        let parent = path
            .parent()
            .expect("generated workspace files have a parent directory");
        fs::create_dir_all(parent)
            .with_context(|| format!("creating directory {}", parent.display()))?;
        fs::write(&path, contents)
            .with_context(|| format!("writing generated file {}", path.display()))?;
    }
    Ok(())
}

fn ensure_generated_workspace_manifest(path: &Path) -> Result<()> {
    match fs::read_to_string(path) {
        Ok(contents) if contents.starts_with(GENERATED_HEADER) => Ok(()),
        Ok(_) => bail!(
            "refusing to overwrite {}: not generated by wr setup",
            path.display()
        ),
        Err(error) if error.kind() == ErrorKind::NotFound => Ok(()),
        Err(error) => Err(error).with_context(|| format!("reading {}", path.display())),
    }
}

fn render_workspace_manifest(
    common: &Dependencies,
    functions: &BTreeMap<String, &Dependencies>,
) -> Result<String> {
    let members: Vec<_> = functions
        .keys()
        .map(|name| format!(".wr/functions/{name}"))
        .collect();
    let workspace = json!({
        "workspace": {
            "members": members,
            "resolver": "3",
            "dependencies": common,
        },
    });
    Ok(format!(
        "{GENERATED_HEADER}{}",
        toml::to_string_pretty(&workspace)?
    ))
}

fn build_function_dependencies(
    name: &str,
    common: &Dependencies,
    local: &Dependencies,
) -> Result<Map<String, Value>> {
    let mut dependencies = Map::new();
    for dependency in common.keys() {
        dependencies.insert(dependency.clone(), json!({ "workspace": true }));
    }
    for (dependency, definition) in local {
        if common.contains_key(dependency) {
            bail!("function {name}: dependency {dependency} is declared both globally and locally");
        }
        dependencies.insert(dependency.clone(), serde_json::to_value(definition)?);
    }
    Ok(dependencies)
}

fn render_function_manifest(name: &str, dependencies: Map<String, Value>) -> Result<String> {
    let manifest = json!({
        "package": {
            "name": format!("wr-function-{name}"),
            "version": "0.1.0",
            "edition": "2024",
            "publish": false,
            "workspace": "../../..",
        },
        "lib": {
            "crate-type": ["cdylib"],
            "path": format!("../../../functions/{name}.rs"),
        },
        "dependencies": dependencies,
    });
    Ok(toml::to_string_pretty(&manifest)?)
}
